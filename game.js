// 新型計時器變數 (Delta-time 基礎，支援精準暫停與恢復)



let lastTimerFrameTime = 0;



let totalElapsedTime = 0; // 毫秒



let isTimerPaused = false;







function startTimer(reset = true) {



    if (reset) {



        totalElapsedTime = 0;



    }



    lastTimerFrameTime = performance.now();



    timerId = requestAnimationFrame(updateTimer);



}







function stopTimer() {



    if (timerId) {



        cancelAnimationFrame(timerId);



        timerId = null;



    }



    finalElapsedTime = totalElapsedTime / 1000;



}







function updateTimer(now) {



    if (!timerId) return;



    



    let dt = now - lastTimerFrameTime;



    lastTimerFrameTime = now;



    



    if (!isTimerPaused) {



        totalElapsedTime += dt;



    }



    



    let totalSeconds = totalElapsedTime / 1000;



    let minutes = Math.floor(totalSeconds / 60);



    let seconds = Math.floor(totalSeconds % 60);



    let milliseconds = Math.floor((totalSeconds % 1) * 1000);



    



    let mm = String(minutes).padStart(2, '0');



    let ss = String(seconds).padStart(2, '0');



    let fff = String(milliseconds).padStart(3, '0');



    



    if (hud.timer) {



        hud.timer.innerText = `${mm}:${ss}.${fff}`;



    }



    



    timerId = requestAnimationFrame(updateTimer);



}







function stopTimer() {



    if (timerId) {



        cancelAnimationFrame(timerId);



        timerId = null;



        finalElapsedTime = (performance.now() - gameStartTime) / 1000;



    }



}







