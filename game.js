// 是否使用線上串流音檔 (true: 從 data_online/ 載入, false: 從 data/ 載入本地音檔版)



const USE_ONLINE_STREAMING = true;







async function loadGameData() {
    try {
        const dataDirectory = USE_ONLINE_STREAMING ? 'data_online/' : 'data/';
        
        // 載入清洗後的生詞對照表以進行字詞合併
        try {
            const vocabRes = await fetch(dataDirectory + 'all_vocabulary_phrases_cleaned.json');
            if (vocabRes.ok) {
                VOCABULARY_PHRASES = await vocabRes.json();
                console.log("成功讀取清洗後的生詞對照表，共 " + VOCABULARY_PHRASES.length + " 個生詞。");
            }
        } catch (ve) {
            console.warn("無法讀取動態生詞檔，將使用字卡拆分模式遊玩。");
        }
        
        const urlParams = new URLSearchParams(window.location.search);
        let fileParam = urlParams.get('file');
        
        if (!fileParam) {
            // 如果沒有指定 URL 檔案參數，則根據下拉選單選擇的腔調來載入對應的合併檔案
            const dialectSelect = document.getElementById('game-dialect-select');
            const dialect = dialectSelect ? dialectSelect.value : 'sixian';
            fileParam = dataDirectory + dialect + '_all.json';
        }
        
        console.log("正在讀取題庫數據：" + fileParam);
        const response = await fetch(fileParam);
        if (!response.ok) throw new Error("Local fetch failed");
        gameData = await response.json();
        console.log("成功載入題庫數據：" + fileParam + "，共 " + (gameData.sentences ? gameData.sentences.length : 0) + " 句。");
    } catch (e) {
        console.warn("無法透過 fetch 讀取本地 JSON (可能是 CORS 阻擋)。使用內嵌 Fallback 數據！");
        gameData = FALLBACK_DATA;
    }
}

function initializeQuestions() {



    questions = [];



    let pool = [...gameData.sentences];



    



    // 隨機打亂題庫池



    pool.sort(() => Math.random() - 0.5);



    



    let selectedSentences = [];



    let usedTargetChars = new Set();



    let usedTargetPinyins = new Set();



    let usedAudios = new Set();



    let usedOriginalSentences = new Set();



    



    for (let sentence of pool) {



        if (selectedSentences.length >= 10) break;



        



        // 確保題目文字與音檔完全不重複



        if (usedOriginalSentences.has(sentence.original_sentence)) continue;



        if (sentence.local_audio && usedAudios.has(sentence.local_audio)) continue;



        



        // 合併連續的客語詞彙字卡



        let mergedWords = mergeVocabulary(sentence.words);



        



        // 篩選出在本次遊戲中「尚未被用作考題目標」的單字與拼音



        let validIndices = [];



        mergedWords.forEach((w, wIdx) => {



            if (w.pinyin && w.pinyin.trim() !== "") {



                if (!usedTargetChars.has(w.char) && !usedTargetPinyins.has(w.pinyin)) {



                    validIndices.push(wIdx);



                }



            }



        });



        



        let bugWordIndex = -1;



        if (validIndices.length > 0) {



            bugWordIndex = validIndices[Math.floor(Math.random() * validIndices.length)];



        } else {



            // 後備方案：如果此句中所有單字都與前面重疊，則放寬限制，但優先保持句子與音檔不重複



            let fallbackIndices = [];



            mergedWords.forEach((w, wIdx) => {



                if (w.pinyin && w.pinyin.trim() !== "") {



                    fallbackIndices.push(wIdx);



                }



            });



            if (fallbackIndices.length > 0) {



                bugWordIndex = fallbackIndices[Math.floor(Math.random() * fallbackIndices.length)];



            }



        }



        



        if (bugWordIndex !== -1) {



            let targetWord = mergedWords[bugWordIndex];



            



            // 記錄已使用的項目



            usedTargetChars.add(targetWord.char);



            usedTargetPinyins.add(targetWord.pinyin);



            if (sentence.local_audio) {



                usedAudios.add(sentence.local_audio);



            }



            usedOriginalSentences.add(sentence.original_sentence);



            



            selectedSentences.push({



                sentence: sentence,



                mergedWords: mergedWords,



                bugWordIndex: bugWordIndex



            });



        }



    }



    



    // 依據選好的 10 題建立題目物件



    selectedSentences.forEach((item, sIdx) => {



        let sentence = item.sentence;



        let mergedWords = item.mergedWords;



        let bugWordIndex = item.bugWordIndex;



        let targetWord = mergedWords[bugWordIndex];



        



        let errorType = 'pinyin';



        let corruptedNode = PinyinModifier.createCorruptedNode(targetWord, errorType);



        



        let gameWords = mergedWords.map((w, wIdx) => {



            if (wIdx === bugWordIndex) {



                return {



                    char: corruptedNode.char,



                    correct_char: corruptedNode.correct_char,



                    current_pinyin: corruptedNode.displayed_pinyin,



                    correct_pinyin: corruptedNode.correct_pinyin,



                    is_punctuation: false,



                    is_bug: true,



                    error_type: corruptedNode.error_type,



                    correct_answer: corruptedNode.correct_answer



                };



            } else {



                let isPunc = !w.pinyin || w.pinyin.trim() === "";



                return {



                    char: w.char,



                    correct_char: w.char,



                    current_pinyin: isPunc ? null : w.pinyin,



                    correct_pinyin: isPunc ? null : w.pinyin,



                    is_punctuation: isPunc,



                    is_bug: false,



                    correct_answer: isPunc ? null : w.pinyin



                };



            }



        });



        



        // 建立可疑字卡索引集合 (suspect_indices)



        let suspectIndices = [bugWordIndex];



        let potentialFakeIndices = [];



        mergedWords.forEach((w, wIdx) => {



            if (wIdx !== bugWordIndex && w.pinyin && w.pinyin.trim() !== "") {



                potentialFakeIndices.push(wIdx);



            }



        });



        if (potentialFakeIndices.length > 0) {



            let count = Math.random() < 0.5 ? 1 : 2;



            count = Math.min(count, potentialFakeIndices.length);



            potentialFakeIndices.sort(() => Math.random() - 0.5);



            let fakeBugIndices = potentialFakeIndices.slice(0, count);



            suspectIndices = suspectIndices.concat(fakeBugIndices);



        }



        suspectIndices.sort((a, b) => a - b);







        questions.push({



            id: sentence.id,



            original_sentence: sentence.original_sentence,



            words: gameWords,



            audio_url: sentence.local_audio,



            bug_word_index: bugWordIndex,



            suspect_indices: suspectIndices,



            correct_pinyin: targetWord.pinyin,



            correct_char: targetWord.char,



            correct_answer: corruptedNode.correct_answer,



            options: corruptedNode.options



        });



    });



}







