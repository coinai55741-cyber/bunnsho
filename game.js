function handleWordCardClick(cardEl, wordIndex) {
    playSFX('click');
    
    const cards = sentenceBox.querySelectorAll('.word-card');
    
    if (currentQuestionIndex < 5) {
        // 1~5 題規則：點對無金色框，選項一直在；點錯計為錯誤並亮紅框 (不變金框)
        if (wordIndex !== currentQuestionData.bug_word_index) {
            cards.forEach((el, idx) => {
                el.classList.remove('selected-error');
            });
            cardEl.classList.add('selected-error');
            currentQuestionMistakes++;
            playSFX('fail');
            triggerIncorrectFeedback("存取被拒：此處未偵測到任何異常數據！", 5);
            
            if (currentQuestionMistakes >= 5) {
                handleQuestionFailed();
            }
        }
    } else {
        // 6~10 題規則：需要玩家先選取字卡（變金色）才渲染並顯示下方補丁選項
        if (wordIndex === currentQuestionData.bug_word_index) {
            selectedWordIndex = wordIndex;
            
            cards.forEach((el, idx) => {
                el.classList.remove('selected', 'selected-error');
                // 還原其他原本亮紅框的可疑字卡
                if (idx !== wordIndex && currentQuestionData.suspect_indices && currentQuestionData.suspect_indices.includes(idx)) {
                    el.classList.add('easy-bug-highlight');
                }
            });
            
            // 移去當前選中卡片的紅框高亮，改為金色選取框 (selected)
            cardEl.classList.remove('easy-bug-highlight');
            cardEl.classList.add('selected');
            
            const wordData = currentQuestionData.words[wordIndex];
            patchIndicator.innerText = `已選擇字卡：[${wordData.char}]`;
            patchIndicator.style.color = "var(--neon-gold)";
            
            // 選對了，渲染並顯示選項！
            renderOptions();
        } else {
            // 選擇正確的字卡（非 bug_word_index），一律判定為錯誤，累加錯誤次數，並清空隱藏選項
            selectedWordIndex = null;
            optionsBox.innerHTML = ''; // 清空補丁選項！
            
            cards.forEach((el, idx) => {
                el.classList.remove('selected', 'selected-error');
                // 還原所有可疑卡片（包括真正的 Bug 卡片）的紅框高亮
                if (currentQuestionData.suspect_indices && currentQuestionData.suspect_indices.includes(idx)) {
                    el.classList.add('easy-bug-highlight');
                }
            });
            
            // 點錯的卡片亮紅色邊框
            cardEl.classList.remove('easy-bug-highlight');
            cardEl.classList.add('selected-error'); 
            
            patchIndicator.innerText = `已選擇字卡：[${currentQuestionData.words[wordIndex].char}]`;
            patchIndicator.style.color = "var(--neon-red)";
            currentQuestionMistakes++;
            
            playSFX('fail');
            triggerIncorrectFeedback("存取被拒：此處未偵測到任何異常數據！", 5);
            
            if (currentQuestionMistakes >= 5) {
                handleQuestionFailed();
            }
        }
    }
}

