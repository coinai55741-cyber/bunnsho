function nextQuestion() {



    if (currentQuestionIndex < questions.length - 1) {



        currentQuestionIndex++;



        



        // 進入第 6 題 (index 5) 時彈出指揮官提示，並暫停時間



        if (currentQuestionIndex === 5) {



            stopTimer();



            stopAudio(); // 確保轉場時音檔停止



            



            const overlay = document.getElementById('commander-alert-overlay');



            if (overlay) {



                overlay.style.display = 'flex';



            } else {



                triggerQuestionTransition(currentQuestionIndex);



            }



        } else {



            triggerQuestionTransition(currentQuestionIndex);



        }



    } else {



        finishGame();



    }



}







