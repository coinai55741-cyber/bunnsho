async function initLessonSelector() {
    try {
        const dataDir = USE_ONLINE_STREAMING ? 'data_online/' : 'data/';
        const res = await fetch(dataDir + 'lessons_list.json');
        if (!res.ok) throw new Error("Failed to load lessons list");
        
        allLessonFiles = await res.json();
        console.log("成功載入全部 " + allLessonFiles.length + " 個課文檔檔案名稱。");
        
        const urlParams = new URLSearchParams(window.location.search);
        const defaultFile = urlParams.get('file');
        if (defaultFile) {
            // 如果 URL 有 file 參數，隱藏腔調選擇器面板
            const selectorPanel = document.querySelector('.lesson-selector-container');
            if (selectorPanel) selectorPanel.style.display = 'none';
        }
    } catch (e) {
        console.error("無法加載關卡選擇器數據，將退回單一預設課文模式:", e);
    }
}

