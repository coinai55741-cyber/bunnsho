function stopBGM() {
    if (!bgmAudio) return;
    bgmAudio.pause();
    bgmAudio = null;
}

function updateSoundButtons() {
    const iconPath = bgmEnabled ? 'assets/images/sound-icon.svg' : 'assets/images/sound-off-icon.svg';
    document.querySelectorAll('.sound-toggle-btn').forEach(btn => {
        const img = btn.querySelector('img');
        if (img) img.src = iconPath;
        btn.classList.toggle('muted', !bgmEnabled);
    });
}

function toggleBGM() {
    bgmEnabled = !bgmEnabled;
    if (bgmEnabled) {
        startBGM();
    } else {
        stopBGM();
    }
    updateSoundButtons();
}

function startBGMFromFirstInteraction() {
    if (!bgmEnabled || bgmAudio) return;
    startBGM();
}







