// 合併句子中的連續字卡為詞組



function mergeVocabulary(words) {



    let result = [];



    let i = 0;



    while (i < words.length) {



        let matchedPhrase = null;



        let matchedLen = 0;



        



        for (let phrase of VOCABULARY_PHRASES) {



            let len = phrase.length;



            if (i + len <= words.length) {



                let segment = words.slice(i, i + len).map(w => w.char).join('');



                if (segment === phrase) {



                    let isValid = words.slice(i, i + len).every(w => w.pinyin && w.pinyin.trim() !== "");



                    if (isValid && len > matchedLen) {



                        matchedPhrase = phrase;



                        matchedLen = len;



                    }



                }



            }



        }



        



        if (matchedPhrase) {



            let segment = words.slice(i, i + matchedLen);



            let mergedPinyin = segment.map(w => w.pinyin).join(' ');



            let custom_wrong_pinyin = segment.map(w => w.custom_wrong_pinyin).filter(Boolean).join(' ') || null;



            let custom_wrong_char = segment.map(w => w.custom_wrong_char).filter(Boolean).join('') || null;



            



            result.push({



                char: matchedPhrase,



                pinyin: mergedPinyin,



                custom_wrong_pinyin: custom_wrong_pinyin,



                custom_wrong_char: custom_wrong_char,



                custom_distractors: []



            });



            i += matchedLen;



        } else {



            result.push(words[i]);



            i++;



        }



    }



    return result;



}







